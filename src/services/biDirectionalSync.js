/**
 * Parses Java source or JSON string and reconstructs Simple Form values
 */
export function parseCodeToSimpleForm(codeText, currentForm = {}) {
  if (!codeText) return currentForm;

  const updated = { ...currentForm };

  // Parse Attack Damage: e.g. ATTACK_DAMAGE = 14.5f or double ATTACK_DAMAGE = 14.5;
  const dmgMatch = codeText.match(/ATTACK_DAMAGE\s*=\s*([0-9.]+)/i);
  if (dmgMatch) {
    const val = parseFloat(dmgMatch[1]);
    if (!isNaN(val)) updated.attackDamage = val;
  }

  // Parse Attack Speed: e.g. ATTACK_SPEED = 1.6f
  const speedMatch = codeText.match(/ATTACK_SPEED\s*=\s*([0-9.]+)/i);
  if (speedMatch) {
    const val = parseFloat(speedMatch[1]);
    if (!isNaN(val)) updated.attackSpeed = val;
  }

  // Parse Durability: e.g. MAX_DURABILITY = 2031 or maxDamage(2031)
  const durMatch = codeText.match(/MAX_DURABILITY\s*=\s*([0-9]+)/i) || codeText.match(/maxDamage\(([0-9]+)\)/i);
  if (durMatch) {
    const val = parseInt(durMatch[1], 10);
    if (!isNaN(val)) updated.durability = val;
  }

  // Parse Knockback: e.g. KNOCKBACK_BONUS = 2.0f or KNOCKBACK = 2.0
  const knockMatch = codeText.match(/KNOCKBACK(?:_BONUS)?\s*=\s*([0-9.]+)/i);
  if (knockMatch) {
    const val = parseFloat(knockMatch[1]);
    if (!isNaN(val)) updated.knockback = val;
  }

  // Parse Armor Defense & Toughness
  const defMatch = codeText.match(/ARMOR_DEFENSE\s*=\s*([0-9]+)/i);
  if (defMatch) {
    const val = parseInt(defMatch[1], 10);
    if (!isNaN(val)) updated.armorDefense = val;
  }
  const toughMatch = codeText.match(/ARMOR_TOUGHNESS\s*=\s*([0-9.]+)/i);
  if (toughMatch) {
    const val = parseFloat(toughMatch[1]);
    if (!isNaN(val)) updated.armorToughness = val;
  }

  // Parse Item ID / Identifier
  const idMatch = codeText.match(/ITEM_IDENTIFIER\s*=\s*"([^"]+)"/i) || codeText.match(/ITEM_ID\s*=\s*"([^"]+)"/i);
  if (idMatch) {
    updated.id = idMatch[1];
  }

  // Fireproof check
  if (codeText.includes('.fireproof()') || codeText.includes('FIRE_RESISTANT = true')) {
    updated.fireResistant = true;
  } else if (codeText.includes('FIRE_RESISTANT = false')) {
    updated.fireResistant = false;
  }

  // Scratch block actions reconstruction
  const detectedBlocks = [];
  detectedBlocks.push({ id: 'evt-1', type: 'event', label: 'On Player Right-Click (use)', eventId: 'right_click' });

  if (codeText.includes('spawnParticles')) {
    detectedBlocks.push({ id: 'act-particles', type: 'action', label: 'Spawn Particles (FLAME)', actionId: 'spawn_particles', param: 'FLAME' });
  }
  if (codeText.includes('addStatusEffect') || codeText.includes('StatusEffects.')) {
    detectedBlocks.push({ id: 'act-potion', type: 'action', label: 'Apply Potion Effect (Speed II)', actionId: 'potion_effect', param: 'SPEED' });
  }
  if (codeText.includes('LIGHTNING_BOLT') || codeText.includes('strikeLightning')) {
    detectedBlocks.push({ id: 'act-lightning', type: 'action', label: 'Strike Lightning', actionId: 'strike_lightning' });
  }
  if (codeText.includes('playSound')) {
    detectedBlocks.push({ id: 'act-sound', type: 'action', label: 'Play Sound Effect', actionId: 'play_sound' });
  }

  if (detectedBlocks.length > 1) {
    updated.scratchBlocks = detectedBlocks;
  }

  return updated;
}
